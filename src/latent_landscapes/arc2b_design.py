"""Frozen Arc 2B prey-effect recoverability design."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

import numpy as np
from scipy.stats import qmc  # type: ignore[import-untyped]

SOBOL_SCRAMBLE_SEED = 20260831
Block = Literal["pilot", "prospective"]
BACKGROUND_HAZARD_REFERENCE = 0.002
REFERENCE_BACKGROUND_RISK = 1.0 - np.exp(-BACKGROUND_HAZARD_REFERENCE * 60.0)


@dataclass(frozen=True, slots=True)
class TruthCondition:
    """One prespecified generating condition."""

    condition_id: str
    design_role: str
    effect_multiplier: float
    background_risk: float
    prey_detection_probability: float

    @property
    def hazard_ratio(self) -> float:
        return self.effect_multiplier

    @property
    def effect(self) -> float:
        return self.effect_multiplier

    @property
    def background_60_day_risk(self) -> float:
        return self.background_risk

    @property
    def prey_detection(self) -> float:
        return self.prey_detection_probability

    @property
    def background_hazard(self) -> float:
        return float(-np.log1p(-self.background_risk) / 60.0)


def _continuous_truths() -> tuple[TruthCondition, ...]:
    engine = qmc.Sobol(d=3, scramble=True, seed=SOBOL_SCRAMBLE_SEED)
    unit = np.asarray(engine.random_base2(m=5), dtype=np.float64)
    return tuple(
        TruthCondition(
            f"S{index:02d}",
            "sobol_pilot" if index <= 16 else "sobol_prospective",
            float(np.exp(np.log(1.5) + float(u_effect) * np.log(6.0 / 1.5))),
            float(0.05 + 0.15 * float(u_background)),
            float(0.35 + 0.50 * float(u_detection)),
        )
        for index, (u_effect, u_background, u_detection) in enumerate(unit, start=1)
    )


CONTINUOUS_TRUTHS = _continuous_truths()
REFERENCE_CONTROL = TruthCondition(
    "R00", "reference_control", 5.0, float(REFERENCE_BACKGROUND_RISK), 0.65
)
NEUTRAL_CONTROL = TruthCondition(
    "N00", "neutral_control", 1.0, float(REFERENCE_BACKGROUND_RISK), 0.65
)


def truths_for_block(block: Block) -> tuple[TruthCondition, ...]:
    """Return one nested 16-condition Sobol block."""
    return CONTINUOUS_TRUTHS[:16] if block == "pilot" else CONTINUOUS_TRUTHS[16:]


def campaign_truths(block: Block) -> tuple[TruthCondition, ...]:
    """Return the conditions generated by a campaign block."""
    truths = truths_for_block(block)
    return (*truths, REFERENCE_CONTROL, NEUTRAL_CONTROL) if block == "pilot" else truths
